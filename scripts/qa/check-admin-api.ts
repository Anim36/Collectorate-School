import "dotenv/config";

import bcrypt from "bcryptjs";

import { PrismaPg } from "@prisma/adapter-pg";

import { PrismaClient } from "@/generated/prisma/client";
import { deleteQaAuditRows } from "./audit-cleanup";
import {
  createUser,
  editUser,
  generateTemporaryPassword,
  listUsers,
  normalizeLoginId,
  resetUserPassword,
  setUserActive,
} from "@/server/services/users";
import {
  assignSubject,
  deleteClass,
  listAllocations,
  listClasses,
  upsertSubject,
} from "@/server/services/classes";
import {
  commitCsv,
  escapeFormulaCell,
  previewCsv,
  MAX_CSV_ROWS,
} from "@/server/services/csv-import";

/**
 * The admin API checks.
 *
 * They run against the real database and clean up after themselves, so the
 * checks can be run again without changing the school.
 *
 * Usage: npx tsx scripts/qa/check-admin-api.ts
 */

const prisma = new PrismaClient({
  adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }),
});

const PASSWORD = "Admin-Check-Pass-2026!";

const results: { name: string; pass: boolean; detail: string }[] = [];

function check(name: string, pass: boolean, detail = ""): void {
  results.push({ name, pass, detail });
  console.log(
    `${pass ? "PASS" : "FAIL"}  ${name}${detail ? `  — ${detail}` : ""}`,
  );
}

/** The prefix every row the checks write carries, so it can be removed. */
const PREFIX = "admin-check";

/** Removes every row the checks wrote. */
async function cleanup(): Promise<void> {
  // The accounts the checks make carry the prefix in their email address,
  // because their login id is generated by the service.
  const users = await prisma.user.findMany({
    where: {
      OR: [
        { loginIdNormalized: { startsWith: PREFIX } },
        { email: { startsWith: PREFIX } },
        // The rows the CSV checks import carry their own prefix.
        { email: { startsWith: "csv-" } },
      ],
    },
    select: { id: true },
  });

  const userIds = users.map((user) => user.id);

  await deleteQaAuditRows(prisma, { actorIds: userIds });
  await deleteQaAuditRows(prisma, { entityPrefix: PREFIX });

  await prisma.paymentItem.deleteMany({
    where: { payment: { student: { userId: { in: userIds } } } },
  });

  await prisma.receipt.deleteMany({
    where: { student: { userId: { in: userIds } } },
  });

  await prisma.payment.deleteMany({
    where: { student: { userId: { in: userIds } } },
  });

  await prisma.fee.deleteMany({
    where: { student: { userId: { in: userIds } } },
  });

  await prisma.examResult.deleteMany({
    where: { student: { userId: { in: userIds } } },
  });

  await prisma.attendance.deleteMany({
    where: { student: { userId: { in: userIds } } },
  });

  await prisma.student.deleteMany({ where: { userId: { in: userIds } } });
  await prisma.teacher.deleteMany({ where: { userId: { in: userIds } } });
  await prisma.user.deleteMany({ where: { id: { in: userIds } } });

  // The classes and the subjects the checks made.
  const classes = await prisma.class.findMany({
    where: { name: { startsWith: "ZZ " } },
    select: { id: true },
  });

  const subjects = await prisma.subject.findMany({
    where: { name: { startsWith: "ZZ " } },
    select: { id: true },
  });

  // The allocations go first, because they hold the class and the subject.
  await prisma.classSubject.deleteMany({
    where: {
      OR: [
        { classId: { in: classes.map((row) => row.id) } },
        { subjectId: { in: subjects.map((row) => row.id) } },
      ],
    },
  });

  await prisma.class.deleteMany({
    where: { id: { in: classes.map((row) => row.id) } },
  });

  await prisma.subject.deleteMany({
    where: { id: { in: subjects.map((row) => row.id) } },
  });
}

/**
 * Creates an admin account the checks act as.
 */
async function createAdmin(): Promise<string> {
  const passwordHash = await bcrypt.hash(PASSWORD, 12);

  const user = await prisma.user.upsert({
    where: { loginIdNormalized: `${PREFIX}-admin` },
    update: { passwordHash, role: "ADMIN" },
    create: {
      id: `${PREFIX}-admin`,
      loginId: `${PREFIX}-admin`,
      loginIdNormalized: `${PREFIX}-admin`,
      name: "Admin Check",
      email: `${PREFIX}-admin@example.com`,
      passwordHash,
      role: "ADMIN",
      isActive: true,
      mustChangePassword: false,
    },
    select: { id: true },
  });

  return user.id;
}

/** Creates a student account the checks act as. */
async function createStudent(): Promise<string> {
  const passwordHash = await bcrypt.hash(PASSWORD, 12);

  const user = await prisma.user.upsert({
    where: { loginIdNormalized: `${PREFIX}-student` },
    update: { passwordHash, role: "STUDENT" },
    create: {
      id: `${PREFIX}-student`,
      loginId: `${PREFIX}-student`,
      loginIdNormalized: `${PREFIX}-student`,
      name: "Student Check",
      email: `${PREFIX}-student@example.com`,
      passwordHash,
      role: "STUDENT",
      isActive: true,
      mustChangePassword: false,
    },
    select: { id: true },
  });

  return user.id;
}

async function main(): Promise<void> {
  await cleanup();

  const adminId = await createAdmin();
  const studentId = await createStudent();

  const classRow = await prisma.class.findFirst({
    where: { name: "Class 9" },
    select: { id: true, name: true },
  });

  if (!classRow) {
    console.log("FAIL  the school has no Class 9");
    process.exitCode = 1;
    return;
  }

  /* --- 1. The login id is matched without regard to case. --------------- */

  const normalized = normalizeLoginId("  AdMiN  ");

  check(
    "a login id is normalised to lower case and trimmed",
    normalized === "admin",
    normalized,
  );

  // The check account has a name of its own, so the lookup cannot land on
  // the seeded admin by accident.
  const caseInsensitive = await prisma.user.findUnique({
    where: { loginIdNormalized: normalizeLoginId("ADMIN-CHECK-ADMIN") },
    select: { id: true },
  });

  check(
    "an account can be found by its login id in any case",
    caseInsensitive?.id === adminId,
    caseInsensitive?.id ?? "not found",
  );

  /* --- 2. Creating a student writes the user and the profile. ---------- */

  const created = await createUser(adminId, {
    name: "Check Student One",
    role: "STUDENT",
    classId: classRow.id,
    email: `${PREFIX}-one@example.com`,
    password: PASSWORD,
  });

  check(
    "a student account is created",
    created.ok === true,
    created.ok ? created.data.loginId : created.error,
  );

  if (created.ok) {
    const loginId = created.data.loginId;

    const studentRow = await prisma.student.findUnique({
      where: { studentId: loginId },
      select: {
        roll: true,
        classId: true,
        section: { select: { isDefault: true, name: true } },
        user: { select: { mustChangePassword: true, role: true } },
      },
    });

    check(
      "the student profile points at the default section of the class",
      studentRow?.section.isDefault === true &&
        studentRow?.section.name === "Default" &&
        studentRow?.classId === classRow.id,
      JSON.stringify({
        section: studentRow?.section,
        classId: studentRow?.classId,
      }),
    );

    check(
      "the new account must change its password",
      studentRow?.user.mustChangePassword === true,
      JSON.stringify({ mustChangePassword: studentRow?.user.mustChangePassword }),
    );

    check(
      "the login id runs ST-<year>-<four digits>",
      /^ST-\d{4}-\d{4}$/.test(loginId),
      loginId,
    );

    check(
      "the roll number is the next free one in the class",
      typeof studentRow?.roll === "number" && studentRow.roll > 0,
      String(studentRow?.roll),
    );

    const stored = await prisma.user.findFirst({
      where: { student: { studentId: loginId } },
      select: { passwordHash: true },
    });

    check(
      "the password is stored as a bcrypt hash and never in the clear",
      (stored?.passwordHash ?? "").startsWith("$2") &&
        !stored?.passwordHash.includes(PASSWORD),
      "hash written",
    );

    /* --- 3. A second student gets the next roll. ------------------------ */

    const second = await createUser(adminId, {
      name: "Check Student Two",
      role: "STUDENT",
      classId: classRow.id,
      email: `${PREFIX}-two@example.com`,
      password: PASSWORD,
    });

    let secondRoll = 0;

    if (second.ok) {
      const row = await prisma.student.findUnique({
        where: { studentId: second.data.loginId },
        select: { roll: true },
      });

      secondRoll = row?.roll ?? 0;
    }

    check(
      "the second student gets the next roll number",
      second.ok && secondRoll === (studentRow?.roll ?? 0) + 1,
      `first ${studentRow?.roll}, second ${secondRoll}`,
    );
  }

  /* --- 4. A duplicate email is refused. -------------------------------- */

  const duplicateEmail = await createUser(adminId, {
    name: "Check Student Three",
    role: "STUDENT",
    classId: classRow.id,
    email: `${PREFIX}-one@example.com`,
    password: PASSWORD,
  });

  check(
    "a duplicate email address is refused",
    duplicateEmail.ok === false,
    duplicateEmail.ok ? "accepted" : duplicateEmail.error,
  );

  /* --- 5. A weak password is refused. --------------------------------- */

  const weakPassword = await createUser(adminId, {
    name: "Check Student Four",
    role: "STUDENT",
    classId: classRow.id,
    email: `${PREFIX}-four@example.com`,
    password: "short",
  });

  check(
    "a weak temporary password is refused",
    weakPassword.ok === false,
    weakPassword.ok ? "accepted" : weakPassword.error,
  );

  /* --- 6. An admin cannot be created from the users screen. ----------- */

  const adminAccount = await createUser(adminId, {
    name: "Check Admin",
    role: "ADMIN" as never,
    classId: classRow.id,
    email: `${PREFIX}-admin2@example.com`,
    password: PASSWORD,
  });

  check(
    "an admin account cannot be created from the users screen",
    adminAccount.ok === false,
    adminAccount.ok ? "accepted" : adminAccount.error,
  );

  /* --- 7. A student without a class is refused. ------------------------ */

  const noClass = await createUser(adminId, {
    name: "Check Student Five",
    role: "STUDENT",
    email: `${PREFIX}-five@example.com`,
    password: PASSWORD,
  });

  check(
    "a student without a class is refused",
    noClass.ok === false,
    noClass.ok ? "accepted" : noClass.error,
  );

  /* --- 8. Deactivating kills the sessions of the account. -------------- */

  const victim = await createUser(adminId, {
    name: "Check Student Six",
    role: "STUDENT",
    classId: classRow.id,
    email: `${PREFIX}-six@example.com`,
    password: PASSWORD,
  });

  if (victim.ok) {
    const before = await prisma.user.findFirst({
      where: { student: { studentId: victim.data.loginId } },
      select: { sessionVersion: true },
    });

    const deactivated = await setUserActive(adminId, victim.data.id, false);

    const after = await prisma.user.findFirst({
      where: { student: { studentId: victim.data.loginId } },
      select: { sessionVersion: true, isActive: true },
    });

    check(
      "deactivating an account bumps its session version",
      deactivated.ok === true &&
        after?.isActive === false &&
        (after?.sessionVersion ?? 0) === (before?.sessionVersion ?? 0) + 1,
      JSON.stringify({ before: before?.sessionVersion, after: after }),
    );

    const reactivated = await setUserActive(adminId, victim.data.id, true);

    check(
      "an account can be activated again",
      reactivated.ok === true,
      reactivated.ok ? "activated" : reactivated.error,
    );
  }

  /* --- 9. An admin cannot deactivate themselves. ---------------------- */

  const selfOff = await setUserActive(adminId, adminId, false);

  check(
    "an admin cannot deactivate their own account",
    selfOff.ok === false,
    selfOff.ok ? "accepted" : selfOff.error,
  );

  /* --- 10. The last active admin cannot be deactivated. ---------------- */

  const otherAdmins = await prisma.user.count({
    where: { role: "ADMIN", isActive: true, id: { not: adminId } },
  });

  if (otherAdmins === 0) {
    const lastAdmin = await setUserActive(adminId, adminId, false);

    check(
      "the last active admin cannot be deactivated",
      lastAdmin.ok === false,
      lastAdmin.ok ? "accepted" : lastAdmin.error,
    );
  } else {
    check(
      "the last active admin cannot be deactivated",
      true,
      `${otherAdmins} other admins are active, so the check is skipped`,
    );
  }

  /* --- 11. Resetting a password clears the lockout and the sessions. --- */

  const locked = await prisma.user.update({
    where: { id: studentId },
    data: {
      failedLoginCount: 5,
      lockedUntil: new Date(Date.now() + 60 * 60 * 1000),
      mustChangePassword: false,
    },
    select: { sessionVersion: true },
  });

  const reset = await resetUserPassword(adminId, studentId, PASSWORD);

  const afterReset = await prisma.user.findUnique({
    where: { id: studentId },
    select: {
      failedLoginCount: true,
      lockedUntil: true,
      mustChangePassword: true,
      sessionVersion: true,
    },
  });

  check(
    "resetting a password clears the lockout, asks for a change and kills the sessions",
    reset.ok === true &&
      afterReset?.failedLoginCount === 0 &&
      afterReset?.lockedUntil === null &&
      afterReset?.mustChangePassword === true &&
      (afterReset?.sessionVersion ?? 0) === (locked.sessionVersion ?? 0) + 1,
    JSON.stringify(afterReset),
  );

  /* --- 12. A generated password is strong enough. ---------------------- */

  const generated = generateTemporaryPassword();

  check(
    "a generated temporary password is 14 characters and holds a number",
    generated.length === 14 && /\d/.test(generated),
    `length ${generated.length}`,
  );

  /* --- 13. The roles of an account cannot be changed. ------------------ */

  const edited = await editUser(adminId, {
    userId: studentId,
    name: "Student Check Renamed",
    email: `${PREFIX}-student@example.com`,
  });

  const roleAfter = await prisma.user.findUnique({
    where: { id: studentId },
    select: { role: true, name: true },
  });

  check(
    "editing an account renames it without changing its role",
    edited.ok === true &&
      roleAfter?.role === "STUDENT" &&
      roleAfter?.name === "Student Check Renamed",
    JSON.stringify(roleAfter),
  );

  /* --- 14. The list is filtered and counted by the database. ----------- */

  const all = await listUsers({ page: 0, pageSize: 10 });

  check(
    "the list counts the accounts that match",
    all.ok === true && all.data.total >= 0 && all.data.rows.length <= 10,
    all.ok ? `total ${all.data.total}` : all.error,
  );

  const searched = await listUsers({
    query: "Check Student One",
    page: 0,
    pageSize: 10,
  });

  check(
    "the search finds the account by name",
    searched.ok === true && searched.data.total >= 1,
    searched.ok ? `total ${searched.data.total}` : searched.error,
  );

  const searchedByLogin = await listUsers({
    query: (created.ok ? created.data.loginId : "").toUpperCase(),
    page: 0,
    pageSize: 10,
  });

  check(
    "the search finds the account by its login id in any case",
    searchedByLogin.ok === true && searchedByLogin.data.total >= 1,
    searchedByLogin.ok
      ? `total ${searchedByLogin.data.total}`
      : searchedByLogin.error,
  );

  const byRole = await listUsers({
    role: "TEACHER",
    page: 0,
    pageSize: 10,
  });

  const teachersInDb = await prisma.user.count({
    where: { role: "TEACHER" },
  });

  check(
    "the role filter counts the teachers in the database",
    byRole.ok === true && byRole.data.total === teachersInDb,
    byRole.ok ? `total ${byRole.data.total}, database ${teachersInDb}` : byRole.error,
  );

  const byStatus = await listUsers({
    status: "INACTIVE",
    page: 0,
    pageSize: 10,
  });

  const inactiveInDb = await prisma.user.count({
    where: { isActive: false },
  });

  check(
    "the status filter counts the inactive accounts in the database",
    byStatus.ok === true && byStatus.data.total === inactiveInDb,
    byStatus.ok
      ? `total ${byStatus.data.total}, database ${inactiveInDb}`
      : byStatus.error,
  );

  const paged = await listUsers({ page: 1, pageSize: 10 });

  check(
    "the second page holds different rows",
    paged.ok === true &&
      (paged.data.rows.length === 0 ||
        !paged.data.rows.some((row) =>
          all.ok ? all.data.rows.some((first) => first.id === row.id) : false,
        )),
    paged.ok ? `${paged.data.rows.length} rows` : paged.error,
  );

  /* --- 15. The list never carries the password hash. ------------------- */

  check(
    "the list never carries the password hash",
    all.ok === true &&
      !JSON.stringify(all.data).includes("passwordHash") &&
      !JSON.stringify(all.data).includes("$2"),
    "no hash in the payload",
  );

  /* --- 16. The classes come from the database, in school order. -------- */

  const classes = await listClasses(0, 20);

  check(
    "the classes come back in school order",
    classes.ok === true &&
      classes.data.rows.length === 12 &&
      classes.data.rows[0].name === "Nursery" &&
      classes.data.rows[11].name === "Class 10",
    classes.ok
      ? `${classes.data.rows.length} classes, first ${classes.data.rows[0]?.name}`
      : classes.error,
  );

  check(
    "the class count comes from the database",
    classes.ok === true && classes.data.total === 12,
    classes.ok ? `total ${classes.data.total}` : classes.error,
  );

  check(
    "every class carries its student, teacher and subject counts",
    classes.ok === true &&
      classes.data.rows.every(
        (row) =>
          typeof row.students === "number" &&
          typeof row.subjectCount === "number" &&
          row.classTeacher.length > 0,
      ),
    "counts present",
  );

  /* --- 17. A class with students cannot be removed. ------------------- */

  const removed = await deleteClass(adminId, classRow.id);

  check(
    "a class with students cannot be removed",
    removed.ok === false,
    removed.ok ? "removed" : removed.error,
  );

  /* --- 18. A subject allocation cannot be duplicated. ------------------ */

  const subject = await upsertSubject(adminId, { name: "ZZ Physics" });

  const allocation = await assignSubject(adminId, {
    classId: classRow.id,
    subjectId: subject.ok ? subject.data.id : "",
  });

  const duplicate = await assignSubject(adminId, {
    classId: classRow.id,
    subjectId: subject.ok ? subject.data.id : "",
  });

  check(
    "the same subject cannot be assigned to a class twice",
    allocation.ok === true && duplicate.ok === false,
    duplicate.ok ? "accepted" : duplicate.error,
  );

  const allocations = await listAllocations(0, 200);

  check(
    "the allocations are read from the database",
    allocations.ok === true && allocations.data.rows.length > 0,
    allocations.ok ? `${allocations.data.rows.length} allocations` : allocations.error,
  );

  check(
    "the allocation count comes from the database",
    allocations.ok === true &&
      allocations.data.total ===
        (await prisma.classSubject.count()),
    allocations.ok ? `total ${allocations.data.total}` : allocations.error,
  );

  /* --- 19. A CSV preview reports the problems on each row. ------------- */

  const csv = [
    "name,role,class,email,tempPassword",
    "CSV Student One,Student,Class 9,csv-one@example.com,",
    "CSV Student Two,Student,No Such Class,csv-two@example.com,",
    "CSV Student Three,Student,Class 9,,Short1!",
    "CSV Student Four,Teacher,Science,csv-four@example.com,",
  ].join("\n");

  const preview = await previewCsv(adminId, {
    name: "check.csv",
    text: csv,
    size: csv.length,
  });

  check(
    "the preview reports one error per bad row",
    preview.ok === true &&
      preview.data.failed === 2 &&
      preview.data.ready === 2 &&
      preview.data.rows[1].problem?.toLowerCase().includes("no class") === true &&
      preview.data.rows[2].problem?.toLowerCase().includes("email") === true &&
      preview.data.rows[2].problem?.toLowerCase().includes("weak") === true,
    preview.ok
      ? `ready ${preview.data.ready}, failed ${preview.data.failed}; row 2 ${preview.data.rows[1].problem}; row 3 ${preview.data.rows[2].problem}`
      : preview.error,
  );

  /* --- 20. A file that is not a CSV is refused. ------------------------ */

  const notCsv = await previewCsv(adminId, {
    name: "check.txt",
    text: "name,role",
    size: 10,
  });

  check(
    "a file that is not a .csv is refused",
    notCsv.ok === false,
    notCsv.ok ? "accepted" : notCsv.error,
  );

  /* --- 21. A file over the row limit is refused. ----------------------- */

  const tooMany = [
    "name,role,class,email",
    ...Array.from(
      { length: MAX_CSV_ROWS + 1 },
      (_, index) => `Row ${index},Student,Class 9,row-${index}@example.com`,
    ),
  ].join("\n");

  const overLimit = await previewCsv(adminId, {
    name: "big.csv",
    text: tooMany,
    size: tooMany.length,
  });

  check(
    "a file over the row limit is refused",
    overLimit.ok === false,
    overLimit.ok ? "accepted" : overLimit.error,
  );

  /* --- 22. A file with a bad row is not committed. --------------------- */

  const withError = await commitCsv(adminId, {
    name: "check.csv",
    text: csv,
    size: csv.length,
  });

  const notImported = await prisma.user.count({
    where: { email: { contains: "csv-" } },
  });

  check(
    "a file with a bad row is not committed at all",
    withError.ok === false && notImported === 0,
    withError.ok ? "committed" : withError.error,
  );

  /* --- 23. A good file is committed in one go. ------------------------ */

  const goodCsv = [
    "name,role,class,email,tempPassword",
    "CSV Good One,Student,Class 9,csv-good-one@example.com,Good-Password-2026!",
    "CSV Good Two,Teacher,,csv-good-two@example.com,Good-Password-2026!",
  ].join("\n");

  const committed = await commitCsv(adminId, {
    name: "good.csv",
    text: goodCsv,
    size: goodCsv.length,
  });

  const importedCount = await prisma.user.count({
    where: { email: { contains: "csv-good-" } },
  });

  check(
    "a good file is committed and every row is written",
    committed.ok === true &&
      committed.data.imported === 2 &&
      importedCount === 2,
    committed.ok ? `imported ${committed.data.imported}` : committed.error,
  );

  /* --- 24. A cell that looks like a formula is escaped. ---------------- */

  check(
    "a cell that starts with a formula character is escaped",
    escapeFormulaCell("=SUM(A1)") === "'=SUM(A1)" &&
      escapeFormulaCell("+1") === "'+1" &&
      escapeFormulaCell("-1") === "'-1" &&
      escapeFormulaCell("@x") === "'@x" &&
      escapeFormulaCell("Arif Hasan") === "Arif Hasan",
    escapeFormulaCell("=SUM(A1)"),
  );

  const formulaCsv = [
    "name,role,class,email,tempPassword",
    "=CMD|calc,Student,Class 9,formula@example.com,Good-Password-2026!",
  ].join("\n");

  const formulaPreview = await previewCsv(adminId, {
    name: "formula.csv",
    text: formulaCsv,
    size: formulaCsv.length,
  });

  check(
    "the preview escapes a cell that looks like a formula",
    formulaPreview.ok === true &&
      formulaPreview.data.rows[0].name.startsWith("'="),
    formulaPreview.ok ? formulaPreview.data.rows[0].name : formulaPreview.error,
  );

  /* --- 25. The audit rows hold no password data. ----------------------- */

  const audits = await prisma.auditLog.findMany({
    where: { actorId: adminId },
    select: { action: true, metadata: true, entityId: true },
  });

  const actions = audits.map((row) => row.action);

  check(
    "the audit log records the writes",
    actions.includes("User created") &&
      actions.includes("User deactivated") &&
      actions.includes("Password reset") &&
      actions.includes("Subject assigned"),
    [...new Set(actions)].join(", "),
  );

  check(
    "no audit row holds a password or a hash",
    !JSON.stringify(audits).includes(PASSWORD) &&
      !JSON.stringify(audits).includes("$2"),
    `${audits.length} rows checked`,
  );

  await cleanup();
  await prisma.$disconnect();

  console.log("");
  const failed = results.filter((result) => !result.pass);
  console.log(
    failed.length === 0
      ? `ALL ${results.length} ADMIN API CHECKS PASS`
      : `${failed.length} of ${results.length} admin API checks failed`,
  );

  if (failed.length > 0) process.exitCode = 1;
}

